--[[
    ZGB_Visuals.lua  —  what a gun with attachments LOOKS like (pure logic).

    Vanilla can draw an attached part on a gun only through 6 part channels
    (Scope, Canon, Stock, Sling, RecoilPad, Clip), one part per channel, at a
    named attachment point of the gun model. So every part is one of:

      RENDERED  has a vanillaPartType and doesn't replace a piece of the gun:
                drawn by vanilla through its channel, at the channel point of
                the gun's CURRENT model (optics, muzzle devices, AR stocks,
                grips, bipods, slings).
      BAKED     everything else with a model (mounts, handguards, adapters,
                lasers, lights, shell holders, recoil pads, stocks that replace
                the original): built into a gun model VARIANT. The variant also
                moves the channel points, e.g. an AK with a side mount gets a
                "scope" point on top of the mount.
      NONE      no model (choke tubes).

    Variants only exist for real combinations the attachment rules allow, and
    are named <GunId>__<BakedPartId>__<BakedPartId> (sorted). They are
    generated by tools/gen_models.lua; the iso view swaps the gun's model to
    the right variant whenever its attachments change.
]]
require "ZGB/ZGB_Core"
require "ZGB/Factory/ZGB_ModelFactory"
require "ZGB/Defs/ZGB_Def_Models"
require "ZGB/Factory/ZGB_PartFactory"
require "ZGB/ZGB_Attachments"

ZGB.Visuals = ZGB.Visuals or {}
local V = ZGB.Visuals
local MF, PF, R = ZGB.ModelFactory, ZGB.PartFactory, ZGB.Attachments

-- part channel -> attachment name in our model scripts
V.CHANNEL_POINT = { Scope = "scope", Canon = "canon", Stock = "stock", Sling = "sling", RecoilPad = "recoilpad", Clip = "clip" }
-- slot kind -> the vanilla channel a rendered part in that slot uses
V.KIND_CHANNEL = { optic = "Scope", muzzle = "Canon", stock = "Stock", sling = "Sling", underbarrel = "RecoilPad", bipod = "RecoilPad" }
V.MAX_VARIANTS = 64

function V.mode(part)
    if part.noModel then return "none" end
    local m = MF.partModel(part)
    if not m then return "none" end
    if part.vanillaPartType and not (m.hides and #m.hides > 0) then return "rendered" end
    return "baked"
end
function V.isBaked(part) return V.mode(part) == "baked" end

local function addv(a, b) return { a[1] + b[1], a[2] + b[2], a[3] + b[3] } end

local function slotOrder(slots)
    local ids = ZGB.sortedKeys(slots)
    table.sort(ids, function(a, b)
        local oa, ob = slots[a].order or 99, slots[b].order or 99
        if oa ~= ob then return oa < ob end
        return a < b
    end)
    return ids
end

--[[ Where everything sits for attachments `att` (slotId -> part full type).
     returns { live = { slotId = { def, pos } }, placed = { { part, slotId, pos, mode } } } ]]
function V.layout(spec, att)
    att = att or {}
    local live, placed, done = {}, {}, {}
    for _, id in ipairs(slotOrder(spec.slots or {})) do
        live[id] = { def = spec.slots[id], pos = MF.slotPoint(spec, id) or { 0, 0, 0 } }
    end
    local changed = true
    while changed do
        changed = false
        for _, slotId in ipairs(ZGB.sortedKeys(att)) do
            local part = PF.get(att[slotId])
            if not done[slotId] and part and live[slotId] then
                done[slotId] = true
                changed = true
                local pos = live[slotId].pos
                placed[#placed + 1] = { part = part, slotId = slotId, pos = pos, mode = V.mode(part) }
                local m = MF.partModel(part)
                for cid, cdef in pairs(part.provides or {}) do
                    local off = (m and m.provides[cid]) or { 0, 0, 0 }
                    live[cid] = { def = cdef, pos = addv(pos, off) }
                end
            end
        end
    end
    return { live = live, placed = placed }
end

--- Baked parts installed, sorted by id.
function V.bakedParts(spec, att)
    local out = {}
    for _, p in ipairs(V.layout(spec, att).placed) do
        if p.mode == "baked" then out[#out + 1] = p.part.id end
    end
    table.sort(out)
    return out
end

--- Model script id of the gun as it looks with `att`.
function V.modelId(spec, att)
    local baked = V.bakedParts(spec, att)
    if #baked == 0 then return spec.id end
    return spec.id .. "__" .. table.concat(baked, "__")
end

--- Gun prim tags hidden by baked parts ("stock", "handguard").
function V.hiddenTags(spec, att)
    local out = {}
    for _, p in ipairs(V.layout(spec, att).placed) do
        local m = p.mode == "baked" and MF.partModel(p.part)
        for _, t in ipairs(m and m.hides or {}) do out[t] = true end
    end
    return out
end

--[[ Every variant the gun can need: each combination of baked parts the
     attachment rules allow (one part per slot, chains followed).
     returns list of att maps (slotId -> fullType), base ({}) first ]]
function V.variants(spec)
    local out, seen = {}, {}
    local function key(att) return V.modelId(spec, att) end
    local function explore(att)
        local k = key(att)
        if seen[k] then return end
        seen[k] = true
        out[#out + 1] = att
        if #out >= V.MAX_VARIANTS then return end
        local lay = V.layout(spec, att)
        for _, slotId in ipairs(ZGB.sortedKeys(lay.live)) do
            if not att[slotId] then
                for _, part in ipairs(PF.all()) do
                    if V.isBaked(part) and R.accepts(lay.live[slotId].def, part) then
                        local nxt = ZGB.copy(att)
                        nxt[slotId] = part.fullType
                        explore(nxt)
                    end
                end
            end
        end
    end
    explore({})
    return out
end

--[[ Full model for a variant: { id, prims, points } where points are named
     after vanilla channels (scope, canon, stock, sling, recoilpad, clip) + world. ]]
function V.variantModel(spec, att)
    local base = MF.gunModel(spec)
    if not base then return nil end
    local lay = V.layout(spec, att)
    local hidden = V.hiddenTags(spec, att)
    local prims = {}
    for _, p in ipairs(base.prims) do
        if not (p.tag and hidden[p.tag]) then prims[#prims + 1] = p end
    end
    local occupied = {}
    for _, pl in ipairs(lay.placed) do
        if pl.mode == "baked" then
            occupied[pl.slotId] = true
            for _, q in ipairs(MF.translate(MF.partModel(pl.part).prims, pl.pos[1], pl.pos[2], pl.pos[3])) do
                prims[#prims + 1] = q
            end
        end
    end
    -- channel points: the first live slot (in slot order) per channel that a baked part doesn't fill
    local points, liveSlots = { world = { 0, 0, 0 } }, {}
    for id, l in pairs(lay.live) do liveSlots[id] = l.def end
    for _, id in ipairs(slotOrder(liveSlots)) do
        local ch = V.KIND_CHANNEL[lay.live[id].def.kind]
        local name = ch and V.CHANNEL_POINT[ch]
        if name and not points[name] and not occupied[id] then points[name] = lay.live[id].pos end
    end
    return { id = V.modelId(spec, att), prims = prims, points = points }
end

--[[ Layers for the Gunsmith preview: the gun sprite, then every installed
     part with a model at its position. Sprites are side views generated by
     tools/gen_models.lua; `sprite` is the texture name under ZGB/Preview/.
     { { sprite, model, pos = {x,y,z} } } in metres from the gun origin ]]
function V.previewLayers(spec, att)
    local hidden = V.hiddenTags(spec, att)
    local suffix = ""
    if hidden.stock then suffix = suffix .. "_nostock" end
    if hidden.handguard then suffix = suffix .. "_nohandguard" end
    local layers = { { sprite = spec.id .. suffix, model = MF.gunModel(spec), pos = { 0, 0, 0 } } }
    for _, pl in ipairs(V.layout(spec, att).placed) do
        if pl.mode ~= "none" then
            layers[#layers + 1] = { sprite = pl.part.id, model = MF.partModel(pl.part), pos = pl.pos, part = pl.part }
        end
    end
    return layers
end

--[[ Pixel rectangles for the preview layers, in the preview sprites' own
     scale (MF.PREVIEW_PPM). The gun sprite's top-left is (0, 0); parts may
     have negative coordinates (a stock behind the gun's rear).
     returns { rects = { { sprite, x, y, w, h } }, bounds = { x0, y0, x1, y1 } } ]]
function V.previewRects(spec, att)
    local ppm, pad = MF.PREVIEW_PPM, MF.PREVIEW_PAD
    local function size(b)
        return math.max(1, math.ceil((b.max[1] - b.min[1]) * ppm + pad * 2)),
               math.max(1, math.ceil((b.max[2] - b.min[2]) * ppm + pad * 2))
    end
    local layers = V.previewLayers(spec, att)
    local gb = MF.bounds(layers[1].model.prims)
    local function gunPx(x, y) return (x - gb.min[1]) * ppm + pad, (gb.max[2] - y) * ppm + pad end
    local rects, x0, y0, x1, y1 = {}, math.huge, math.huge, -math.huge, -math.huge
    for i, l in ipairs(layers) do
        local b = i == 1 and gb or MF.bounds(l.model.prims)
        local w, h = size(b)
        local x, y = 0, 0
        if i > 1 then
            local px, py = gunPx(l.pos[1], l.pos[2])
            x = px - ((0 - b.min[1]) * ppm + pad)
            y = py - ((b.max[2] - 0) * ppm + pad)
        end
        rects[#rects + 1] = { sprite = l.sprite, x = x, y = y, w = w, h = h }
        x0, y0 = math.min(x0, x), math.min(y0, y)
        x1, y1 = math.max(x1, x + w), math.max(y1, y + h)
    end
    return { rects = rects, bounds = { x0, y0, x1, y1 } }
end

--- The vanilla visual twin of a rendered part (a WeaponPart item that only draws).
function V.twinOf(part) return ZGB.MODULE .. ".Vis_" .. part.id end

return V
