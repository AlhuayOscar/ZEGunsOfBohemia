"""
fetch.py  -  downloads the picked Sketchfab models into .cache/model_sources/sketchfab/.

    set SKETCHFAB_API_TOKEN=<your token>        (sketchfab.com -> Settings -> Password & API)
    "<blender>/5.2/python/bin/python.exe" -I tools/sketchfab/fetch.py [ids...]

Sketchfab's download API needs an account token; the token is read from the environment
only, never written anywhere or printed. Picks come from tools/sketchfab/picks.lua
(our id = { uid = "<model uid>", fix = {...} }). For each pick it:
  1. reads the model's public page data (name, author, license) and REFUSES anything that
     is not CC0 or CC-BY (the mod ships the converted model, see tools/model_sources.lua),
  2. downloads the glb (or the gltf zip) to sketchfab/<uid>.glb / <uid>.zip,
  3. writes sketchfab/<uid>.json, and the credit (title, author, license, url) into
     tools/sketchfab/credits.lua, which is checked in: CREDITS.txt is built from it, so the
     credits never depend on someone's download cache.
Already downloaded models are skipped, so a stopped run just picks up where it was.
Every line it prints also goes to .cache/sketchfab/fetch.log (failures and their reason).
`--credits-only` rewrites credits.lua from the downloads without a token.
"""
import json, os, re, sys, time, urllib.error, urllib.request, zipfile

REPO = os.getcwd()
OUT = os.path.join(REPO, ".cache", "model_sources", "sketchfab")
PICKS = os.path.join(REPO, "tools", "sketchfab", "picks.lua")
CREDITS = os.path.join(REPO, "tools", "sketchfab", "credits.lua")
API = "https://api.sketchfab.com/v3/models/"
OK = {"CC Attribution": "CC-BY 4.0", "CC0 Public Domain": "CC0 1.0"}


def get(url, token=None, tries=5):
    """GET with retries: Sketchfab answers 429 when asked too fast, and big files time out."""
    headers = {"User-Agent": "ZEGunsOfBohemia-model-fetch"}
    if token: headers["Authorization"] = "Token " + token
    for k in range(tries):
        try:
            with urllib.request.urlopen(urllib.request.Request(url, headers=headers), timeout=300) as r:
                return r.read()
        except urllib.error.HTTPError as e:
            if e.code not in (429, 500, 502, 503, 504) or k == tries - 1: raise
            wait = int(e.headers.get("Retry-After") or 0) or 10 * (k + 1)
            print("     (Sketchfab says %d, waiting %d s)" % (e.code, wait), flush=True); time.sleep(wait)
        except (urllib.error.URLError, TimeoutError, ConnectionError):
            if k == tries - 1: raise
            time.sleep(5 * (k + 1))


sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))   # -I leaves the script's folder out
import check_rips


def rip_signs(path, uid):
    """First sign that a download is ripped from a game (check_rips.py), or None."""
    if uid in check_rips.REJECTED: return check_rips.REJECTED[uid]
    doc = {}
    if path.endswith(".glb"): doc = check_rips.glb_json(path)
    elif os.path.exists(os.path.join(OUT, uid, "scene.gltf")):
        doc = json.load(open(os.path.join(OUT, uid, "scene.gltf"), encoding="utf-8"))
    for n in check_rips.names(doc):
        for pat, why in check_rips.PATTERNS:
            if "by hand" in why: continue                # only sure signs delete a download
            if re.search(pat, n, re.I): return "%s ('%s')" % (why, n)
    return None


LOG = os.path.join(REPO, ".cache", "sketchfab", "fetch.log")
_print = print
def print(*a, **k):
    """Console and .cache/sketchfab/fetch.log (never the token: it is not in any message)."""
    _print(*a, **k)
    os.makedirs(os.path.dirname(LOG), exist_ok=True)
    with open(LOG, "a", encoding="utf-8") as f: f.write(" ".join(str(x) for x in a) + chr(10))


def lua_str(v):
    return '"' + str(v or "").replace("\\", "\\\\").replace('"', '\\"') + '"'


def write_credits():
    """tools/sketchfab/credits.lua from every downloaded model's meta json."""
    rows = []
    for n in sorted(os.listdir(OUT)):
        if not n.endswith(".json"): continue
        m = json.load(open(os.path.join(OUT, n), encoding="utf-8"))
        rows.append('    ["%s"] = { title = %s, author = %s, license = %s, url = %s, file = %s },' % (
            m["uid"], lua_str(m["name"]), lua_str(m["author"]), lua_str(m["license"]), lua_str(m["url"]), lua_str(m["file"])))
    head = ["-- GENERATED by tools/sketchfab/fetch.py: credit data of every downloaded Sketchfab model, by uid.",
            "-- tools/model_sources.lua and CREDITS.txt read it. Do not edit by hand.", "return {"]
    open(CREDITS, "w", encoding="utf-8").write("\n".join(head + rows + ["}", ""]))


def main():
    if "--credits-only" in sys.argv:                 # rebuild credits.lua from what is downloaded
        os.makedirs(OUT, exist_ok=True); write_credits(); print("wrote", CREDITS); return
    token = os.environ.get("SKETCHFAB_API_TOKEN")
    if not token:
        sys.exit("Set SKETCHFAB_API_TOKEN (your Sketchfab API token) first.")
    os.makedirs(OUT, exist_ok=True)
    picks = dict(re.findall(r'(\w+)\s*=\s*\{\s*uid\s*=\s*"([0-9a-f]{32})"', open(PICKS, encoding="utf-8").read()))
    only = set(sys.argv[1:])
    done = failed = 0
    for iid, uid in sorted(picks.items()):
        if iid.startswith("_") or (only and iid not in only): continue
        meta_path = os.path.join(OUT, uid + ".json")
        if os.path.exists(meta_path): continue
        try:
            info = json.loads(get(API + uid))
            lic = (info.get("license") or {}).get("label")
            if lic not in OK:
                print("SKIP %-22s %s: license '%s' is not CC0 / CC-BY" % (iid, uid, lic)); failed += 1; continue
            links = json.loads(get(API + uid + "/download", token))
            if "glb" in links:
                path = os.path.join(OUT, uid + ".glb"); open(path, "wb").write(get(links["glb"]["url"]))
            else:
                path = os.path.join(OUT, uid + ".zip"); open(path, "wb").write(get(links["gltf"]["url"]))
                with zipfile.ZipFile(path) as z:
                    for n in z.namelist():                         # extract only inside the model's folder
                        if n.startswith("/") or ".." in n.replace("\\", "/").split("/"): continue
                        z.extract(n, os.path.join(OUT, uid))
            rip = rip_signs(path, uid)
            if rip:                                          # a game's model with a CC label: never ship it
                os.remove(path)
                print("RIP  %-22s %s: %s - deleted, pick another" % (iid, uid, rip), flush=True); failed += 1; continue
            user = info.get("user") or {}
            json.dump({"uid": uid, "name": info.get("name"), "author": user.get("displayName") or user.get("username"),
                       "username": user.get("username"), "license": OK[lic], "url": info.get("viewerUrl"),
                       "file": os.path.basename(path)}, open(meta_path, "w", encoding="utf-8"), indent=1)
            print("OK   %-22s %s (%s, %s)" % (iid, info.get("name"), user.get("displayName"), OK[lic]), flush=True); done += 1
            write_credits()                          # after every model: a stopped run keeps its credits
            time.sleep(1)
        except Exception as e:
            print("FAIL %-22s %s: %s" % (iid, uid, e), flush=True); failed += 1
    write_credits()
    print("%d downloaded, %d failed or skipped" % (done, failed))


if __name__ == "__main__":
    main()
