--[[
    Builds the mod's sounds from the CC0 recordings listed in
    Defs/ZGB_Def_Sounds.lua (downloads in .cache/sound_sources/, see the
    `url` of each source):

        lua5.1 tools/gen_sounds.lua

    For every family: the shot is cut from its start, kept for `len` seconds
    with a fading tail, pitched if asked, made mono 44.1 kHz, loudness
    normalised and saved as Ogg Vorbis; a suppressed version is filtered and
    quieter. Mechanical sounds are cut out of the reload recordings at their
    silent gaps. Writes:

        media/sound/ZGB/*.ogg          (Core)
        media/scripts/ZGB_sounds.txt   sound scripts (GENERATED)

    Needs ffmpeg + ffprobe: on PATH, or set ZGB_FFMPEG_DIR.
    VERIFY in game: the sound script syntax and that names resolve globally.
]]
local CORE = "Contents/mods/ZEGunsOfBohemiaCore/42/media/"
package.path = CORE .. "lua/shared/?.lua;" .. package.path
local realPrint = print
print = function() end
require "ZGB/Defs/ZGB_Def_Sounds"
print = realPrint
local SND = ZGB.Sounds

local isWindows = package.config:sub(1, 1) == "\\"
local function findTool(name)
    local dir = os.getenv("ZGB_FFMPEG_DIR")
    if dir then return dir .. "/" .. name end
    local winget = (os.getenv("LOCALAPPDATA") or "") .. "/Microsoft/WinGet/Packages/Gyan.FFmpeg_Microsoft.Winget.Source_8wekyb3d8bbwe"
    local p = io.popen(isWindows and ('dir /b /s "' .. winget:gsub("/", "\\") .. '\\' .. name .. '.exe" 2>nul') or ("command -v " .. name))
    local found = p and p:read("*l"); if p then p:close() end
    return found or name
end
local FFMPEG, FFPROBE = findTool("ffmpeg"), findTool("ffprobe")
local function q(s) return '"' .. s .. '"' end
local function run(cmd)
    local full = isWindows and ('"' .. cmd .. '"') or cmd        -- cmd.exe needs the whole line quoted
    return os.execute(full)
end
local function capture(cmd)
    local p = io.popen((isWindows and ('"' .. cmd .. '"') or cmd) .. " 2>&1")
    local out = p:read("*a"); p:close(); return out
end

local OUT = CORE .. "sound/ZGB/"
if isWindows then os.execute('mkdir "' .. OUT:gsub("/", "\\") .. '" 2>nul') else os.execute('mkdir -p "' .. OUT .. '"') end

local function sampleRate(file)
    local out = capture(q(FFPROBE) .. " -v error -select_streams a:0 -show_entries stream=sample_rate -of csv=p=0 " .. q(file))
    return tonumber(out:match("%d+")) or 44100
end

--- Non-silent segments { {start, stop} } of a file.
local function segments(file)
    local out = capture(q(FFMPEG) .. " -hide_banner -i " .. q(file) .. " -af silencedetect=n=-38dB:d=0.06 -f null -")
    local dur = tonumber(out:match("Duration: %d+:%d+:([%d%.]+)")) or 999
    local segs, cursor = {}, 0
    for kind, t in out:gmatch("silence_(%a+): ([%d%.]+)") do
        t = tonumber(t)
        if kind == "start" then
            if t - cursor > 0.02 then segs[#segs + 1] = { cursor, t } end
        elseif kind == "end" then cursor = t end
    end
    if dur - cursor > 0.02 and cursor > 0 then segs[#segs + 1] = { cursor, dur } end
    return segs
end

-- one channel, not a mix: the library records each shot with two different microphones, and
-- averaging them (0.5*c0+0.5*c1) partly cancelled out (L-R louder than either side) and sounded
-- like the suppressed and the plain shot together in game. Channel 1 is the closer, louder mic.
local MONO = "pan=mono|c0=c0"
local function encode(src, filters, dst)
    local cmd = q(FFMPEG) .. " -hide_banner -loglevel error -y -i " .. q(src) .. ' -af "' .. filters ..
                '" -ar 44100 -ac 1 -c:a libvorbis -q:a 5 ' .. q(dst)
    assert(run(cmd), "ffmpeg failed: " .. dst)
end

local scripts = { "/*\n    ZE Guns Of Bohemia - sounds.\n    GENERATED by tools/gen_sounds.lua from ZGB_Def_Sounds.lua - do not edit by hand.\n",
                  "    Recordings: CC0 (see CREDITS.txt).\n" ..
                  "    Same layout as vanilla's sound scripts: module Base (a sound in module ZGB played\n" ..
                  "    nothing in game), file clips, no loop / is3D fields.\n*/\nmodule Base\n{\n" }
local function script(name, file, distance, volume)
    scripts[#scripts + 1] = string.format(
        "\n    sound %s\n    {\n        category = Item,\n        maxInstancesPerEmitter = 2,\n        clip\n        {\n            file = media/sound/ZGB/%s,\n            distanceMax = %d,\n            volume = %.2f,\n        }\n    }\n",
        name, file, distance, volume)
end

local n = 0
-- ---------------------------------------------------------------- gunshots
for _, fam in ipairs((function() local k = {} for f in pairs(SND.FAMILIES) do k[#k + 1] = f end table.sort(k) return k end)()) do
    local f = SND.FAMILIES[fam]
    local src = SND.SOURCES.ffsl.dir .. "/" .. f.src
    local sr = sampleRate(src)
    local pitch = f.pitch and string.format("asetrate=%d,", math.floor(sr * f.pitch)) or ""
    local len = f.len
    local base = "silenceremove=start_periods=1:start_threshold=-30dB,asetpts=PTS-STARTPTS," .. pitch ..
                 string.format("atrim=0:%.2f,afade=t=out:st=%.2f:d=%.2f,", len, len * 0.3, len * 0.7) .. MONO
    local file = "fire_" .. fam:lower() .. ".ogg"
    encode(src, base .. ",loudnorm=I=-12:TP=-1:LRA=7", OUT .. file)
    script(SND.fireName(fam), file, 120, 1.0)
    -- Suppressed: a short, sharp "thup" with no tail. The first version (same shot, lowpass 1400 Hz,
    -- half length) kept a long dull tail and sounded like a muffled shot on top of a plain one
    -- (sixth in-game test); cut to 0.35 s it then sounded like a dry click (seventh). Now: 0.8 s
    -- with a linear fade from 60 ms (an exponential one left -35 dB right after the crack: a click),
    -- so a short dull decay stays audible under the crack; the low boom cut
    -- (highpass 300 Hz, -8 dB at 150 Hz), the crack kept but softened (lowpass 4.5 kHz), ~8 dB under.
    local supLen = math.min(0.8, len)
    local sup = "silenceremove=start_periods=1:start_threshold=-30dB,asetpts=PTS-STARTPTS," .. pitch ..
                string.format("atrim=0:%.2f,afade=t=out:st=0.06:d=%.2f:curve=tri,", supLen, supLen - 0.06) .. MONO ..
                ",highpass=f=300,equalizer=f=150:t=q:w=1:g=-8,lowpass=f=4500,loudnorm=I=-20:TP=-4:LRA=5"
    local sfile = "firesup_" .. fam:lower() .. ".ogg"
    encode(src, sup, OUT .. sfile)
    script(SND.suppressedName(fam), sfile, 40, 1.0)
    n = n + 2
end

-- ---------------------------------------------------------------- mechanics
for _, name in ipairs({ "MagOut", "MagIn", "Rack", "Pump", "ShellInsert" }) do
    local m = SND.MECHANICS[name]
    local src = SND.SOURCES.zer0_sol.dir .. "/" .. m.src
    local filters
    if m.segment then
        local seg = segments(src)[m.segment]
        assert(seg, name .. ": segment " .. m.segment .. " not found in " .. m.src)
        -- asetpts: start the clip at 0, or players get the leading silence back
        filters = string.format("atrim=%.3f:%.3f,asetpts=PTS-STARTPTS,", math.max(0, seg[1] - 0.02), seg[2] + 0.05)
    else
        filters = "silenceremove=start_periods=1:start_threshold=-38dB,atrim=0:1.2,asetpts=PTS-STARTPTS,"
    end
    filters = filters .. MONO .. ",loudnorm=I=-18:TP=-2:LRA=7"
    local file = "mech_" .. name:lower() .. ".ogg"
    encode(src, filters, OUT .. file)
    script(SND.mechName(name), file, 15, 0.8)
    n = n + 1
end

scripts[#scripts + 1] = "}\n"
local fh = assert(io.open(CORE .. "scripts/ZGB_sounds.txt", "wb")); fh:write(table.concat(scripts)); fh:close()
dofile("tools/gen_credits.lua")
print(string.format("wrote %d sounds to %s and scripts/ZGB_sounds.txt", n, OUT))
