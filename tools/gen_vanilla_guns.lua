--[[
    Copies the item fields of vanilla B42 guns out of the installed game into
    tools/data/vanilla_guns.lua (committed, so gen_scripts works without the game):

        lua5.1 tools/gen_vanilla_guns.lua      (after a game update)

    gen_scripts.lua gives every ZGB gun the fields of its vanilla template gun
    (VANILLA_TEMPLATE there): fire mode, rack after shot, chamber, swing time,
    aim cone, muzzle flash, equip/aim/jam/casing sounds... everything except
    what the factory owns. The first in-game test showed what happens without
    them: no recoil, no muzzle flash, wrong timing.
]]
local PZ = os.getenv("PZ_DIR") or "C:/Program Files (x86)/Steam/steamapps/common/ProjectZomboid"
local SRC = PZ .. "/media/scripts/generated/items/weapon.txt"
local OUT = "tools/data/vanilla_guns.lua"
local GUNS = { "Pistol", "Revolver", "AssaultRifle", "AssaultRifle2", "HuntingRifle", "L94_Rifle",
               "Shotgun", "DoubleBarrelShotgun" }

local f = assert(io.open(SRC, "rb"), "game not found at " .. PZ .. " (set PZ_DIR)")
local text = f:read("*a"):gsub("\r", ""); f:close()
local build = "?"
do
    local p = io.popen(package.config:sub(1, 1) == "\\" and ('dir /b "' .. PZ:gsub("/", "\\") .. '"') or ('ls "' .. PZ .. '"'))
    build = (p:read("*a")):match("(%d+%.%d+%.%d+)") or "?"; p:close()
end

local out = { "-- GENERATED by tools/gen_vanilla_guns.lua from the game's weapon.txt (build " .. build .. ").",
              "-- Do not edit by hand: rerun after a game update.",
              "return {" }
for _, gun in ipairs(GUNS) do
    local body = text:match("\n%s*item%s+" .. gun .. "%s*\n%s*{(.-)\n%s*}")
    assert(body, "vanilla item " .. gun .. " not found in " .. SRC)
    out[#out + 1] = string.format("    %s = {", gun)
    -- a list, not a map: keys can repeat (ModelWeaponPart)
    for line in body:gmatch("[^\n]+") do
        local k, v = line:match("^%s*([%w_]+)%s*=%s*(.-)%s*,?%s*$")
        if k then out[#out + 1] = string.format("        { %q, %q },", k, (v:gsub(",$", ""))) end
    end
    out[#out + 1] = "    },"
end
out[#out + 1] = "}"
os.execute(package.config:sub(1, 1) == "\\" and 'mkdir "tools\\data" 2>NUL' or 'mkdir -p tools/data')
local w = assert(io.open(OUT, "wb")); w:write(table.concat(out, "\n"), "\n"); w:close()
print(string.format("wrote %s: %d vanilla guns (build %s)", OUT, #GUNS, build))
