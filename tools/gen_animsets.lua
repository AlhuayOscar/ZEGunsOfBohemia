--[[
    Generates DRAFT AnimSet nodes for the isometric view from the animation
    factory (anim types x holding stances, plus fire nodes per kick class):

        lua5.1 tools/gen_animsets.lua      -> docs/animsets/iso/<state>/ZGB_*.xml

    They are drafts on purpose: the node format and the vanilla clip names
    are unverified, and a malformed AnimSet must never reach players. Once the
    first in-game test confirms the format (README VERIFY list), copy the
    folders into Contents/mods/ZEGunsOfBohemiaIso/42/media/AnimSets/player/.

    Each node only matches when our variables are set (ZGB_AnimType,
    ZGB_Stance, ZGB_Kick), which the iso addon does for ZGB guns only, so
    vanilla guns keep vanilla animation.
]]
local CORE = "Contents/mods/ZEGunsOfBohemiaCore/42/media/lua/shared/"
local ISO  = "Contents/mods/ZEGunsOfBohemiaIso/42/media/lua/shared/"
local HOLD = "Contents/mods/ZEGunsOfBohemiaHolding/42/media/lua/shared/"
package.path = CORE .. "?.lua;" .. ISO .. "?.lua;" .. HOLD .. "?.lua;" .. package.path
local realPrint = print
print = function() end
require "ZGB/Defs/ZGB_Def_Weapons"
require "ZGBIso/ZGB_Def_IsoView"
require "ZGBHolding/ZGB_Holding"
print = realPrint

local AF, H = ZGB.AnimFactory, ZGB.Holding
local OUT = arg[1] or "docs/animsets/iso/"
local isWindows = package.config:sub(1, 1) == "\\"

local function mkdir(path)
    if isWindows then os.execute('mkdir "' .. path:gsub("/", "\\") .. '" 2>nul')
    else os.execute('mkdir -p "' .. path .. '"') end
end

local function cond(name, value)
    return string.format("    <m_Conditions>\n        <m_Name>%s</m_Name>\n        <m_Type>STRING</m_Type>\n        <m_StringValue>%s</m_StringValue>\n    </m_Conditions>\n", name, value)
end

local function node(name, clip, conds, note)
    local out = { '<?xml version="1.0" encoding="utf-8"?>\n',
        "<!-- DRAFT generated by tools/gen_animsets.lua from the animation factory. " .. (note or "") .. " VERIFY before shipping. -->\n",
        "<animNode>\n",
        string.format("    <m_Name>%s</m_Name>\n", name),
        string.format("    <m_AnimName>%s</m_AnimName>\n", clip.anim),
        string.format("    <m_SpeedScale>%.2f</m_SpeedScale>\n", clip.speed or 1),
        "    <m_BlendTime>0.25</m_BlendTime>\n",
        "    <m_Priority>10</m_Priority>\n" }
    for _, c in ipairs(conds) do out[#out + 1] = cond(c[1], c[2]) end
    out[#out + 1] = "</animNode>\n"
    return table.concat(out)
end

local count = 0
local function write(state, name, text)
    mkdir(OUT .. state)
    local f = assert(io.open(OUT .. state .. "/" .. name .. ".xml", "w"))
    f:write(text); f:close()
    count = count + 1
end

for _, t in ipairs(AF.types()) do
    for _, state in ipairs({ "idle", "aim" }) do
        for _, s in ipairs(H.all()) do
            local clip = AF.resolve("iso", t.id, state, s.id)
            if clip then
                local name = string.format("ZGB_%s_%s_%s", t.id, state, s.id)
                write(state, name, node(name, clip, { { "ZGB_AnimType", t.id }, { "ZGB_Stance", s.id } },
                    string.format("lowered=%.2f sway=%.2f.", clip.lowered or 0, clip.sway or 1)))
            end
        end
    end
    local fire = AF.resolve("iso", t.id, "fire")
    for kick, speed in pairs({ light = 1.15, medium = 1.0, heavy = 0.85 }) do
        local name = string.format("ZGB_%s_fire_%s", t.id, kick)
        write("fire", name, node(name, { anim = fire.anim, speed = speed },
            { { "ZGB_AnimType", t.id }, { "ZGB_Kick", kick } }, "Heavier kick plays the shot slower and bigger."))
    end
end
print(string.format("wrote %d draft AnimSet nodes to %s", count, OUT))
