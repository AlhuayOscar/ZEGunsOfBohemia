--[[
    Generates AnimSet nodes for the isometric view from the animation
    factory (anim types x holding stances, plus fire nodes per kick class):

        lua5.1 tools/gen_animsets.lua
          idle + aim  -> docs/animsets/iso/<state>/   (drafts: NOT shipped, see below)
          fire        -> docs/animsets/iso/fire/                                           (draft)

    Nothing here ships. Third in-game test: x_extends="aim_rifle.xml" is looked
    up in OUR mod's folder, not the game's, so every node failed to parse (288
    errors) and the guns could not aim or fire. A node that ships must be
    complete on its own (validate_mod enforces it); until stance nodes are
    written that way and checked in game, they stay drafts.

    Each node only matches when our variables are set (ZGB_AnimType,
    ZGB_Stance, ZGB_Kick), which the iso addon does for ZGB guns only, so
    vanilla guns keep vanilla animation.
]]
local CORE = "Contents/mods/ZEGunsOfBohemiaCore/42/media/lua/shared/"
local ISO  = "Contents/mods/ZEGunsOfBohemiaIso/42/media/lua/shared/"
local HOLD = "Contents/mods/ZEGunsOfBohemiaHolding/42/media/lua/shared/"
package.path = CORE .. "?.lua;" .. ISO .. "?.lua;" .. HOLD .. "?.lua;" .. package.path
local realPrint = print
print = function() end
require "ZGB/Defs/ZGB_Def_Weapons"
require "ZGBIso/ZGB_Def_IsoView"
require "ZGBHolding/ZGB_Holding"
print = realPrint

local AF, H = ZGB.AnimFactory, ZGB.Holding
local OUT = arg[1] or "docs/animsets/iso/"

local isWindows = package.config:sub(1, 1) == "\\"

local function mkdir(path)
    if isWindows then os.execute('mkdir "' .. path:gsub("/", "\\") .. '" 2>nul')
    else os.execute('mkdir -p "' .. path .. '"') end
end

local function cond(name, value)
    return string.format("    <m_Conditions>\n        <m_Name>%s</m_Name>\n        <m_Type>STRING</m_Type>\n        <m_StringValue>%s</m_StringValue>\n    </m_Conditions>\n", name, value)
end

-- Holding nodes EXTEND the vanilla node (pose, up/down aim blends, transitions, firing)
-- and only change its speed: the first in-game test showed that replacing it with one
-- clip gives the wrong hold and no recoil. Vanilla chains nodes the same way
-- (IdleRifle extends Idle.xml, aim_rifle extends aim.xml).
local VANILLA_NODE = {
    idle = { Handgun = "IdleHandgun.xml", Rifle = "IdleRifle.xml" },
    aim  = { Handgun = "aim_handgun.xml", Rifle = "aim_rifle.xml" },
}

local function node(name, clip, conds, note, extends)
    local out = { '<?xml version="1.0" encoding="utf-8"?>\n',
        "<!-- GENERATED by tools/gen_animsets.lua from the animation factory. " .. (note or "") .. " -->\n",
        extends and string.format('<animNode x_extends="%s">\n', extends) or "<animNode>\n",
        string.format("    <m_Name>%s</m_Name>\n", name) }
    if not extends then out[#out + 1] = string.format("    <m_AnimName>%s</m_AnimName>\n", clip.anim) end
    out[#out + 1] = string.format("    <m_SpeedScale>%.2f</m_SpeedScale>\n", clip.speed or 1)
    out[#out + 1] = "    <m_BlendTime>0.25</m_BlendTime>\n"
    out[#out + 1] = "    <m_Priority>10</m_Priority>\n"
    for _, c in ipairs(conds) do out[#out + 1] = cond(c[1], c[2]) end
    out[#out + 1] = "</animNode>\n"
    return table.concat(out)
end

local count = 0
local function write(state, name, text)
    local dir = OUT                     -- drafts only (see the header)
    mkdir(dir .. state)
    local f = assert(io.open(dir .. state .. "/" .. name .. ".xml", "w"))
    f:write(text); f:close()
    count = count + 1
end


for _, t in ipairs(AF.types()) do
    local params = AF.scriptParams("iso", t.id)
    for _, state in ipairs({ "idle", "aim" }) do
        for _, s in ipairs(H.all()) do
            local clip = AF.resolve("iso", t.id, state, s.id)
            if clip then
                local name = string.format("ZGB_%s_%s_%s", t.id, state, s.id)
                local extends = assert(VANILLA_NODE[state][params.SwingAnim], "no vanilla node for " .. params.SwingAnim)
                write(state, name, node(name, clip, { { "ZGB_AnimType", t.id }, { "ZGB_Stance", s.id } },
                    string.format("Vanilla %s at speed %.2f.", extends, clip.speed or 1), extends))
            end
        end
    end
    local fire = AF.resolve("iso", t.id, "fire")
    for kick, speed in pairs({ light = 1.15, medium = 1.0, heavy = 0.85 }) do
        local name = string.format("ZGB_%s_fire_%s", t.id, kick)
        write("fire", name, node(name, { anim = fire.anim, speed = speed },
            { { "ZGB_AnimType", t.id }, { "ZGB_Kick", kick } }, "Heavier kick plays the shot slower and bigger."))
    end
end
print(string.format("wrote %d AnimSet node drafts to %s (nothing shipped)", count, OUT))
