-- ---------------------------------------------------------------- ammo
-- per caliber first, then per caliber group
local ICONS = { ["22lr"] = "Bullets9mm", ["9x19"] = "Bullets9mm", ["38spl"] = "Bullets38", ["45acp"] = "Bullets45",
                ["45colt"] = "Bullets45", ["44mag"] = "Bullets44",
                pistol = "Bullets9mm", revolver = "Bullets38", rifle = "556Bullets", full_rifle = "308Bullets",
                magnum_rifle = "308Bullets", shotgun = "ShotgunShells" }
local WEIGHT = { ["22lr"] = 0.005, ["50bmg"] = 0.12, ["338lm"] = 0.05,
                 pistol = 0.012, revolver = 0.015, rifle = 0.015, full_rifle = 0.03, magnum_rifle = 0.05, shotgun = 0.04 }

out = { [[
/*
    ZE Guns Of Bohemia - ammo variant items.
    GENERATED by tools/gen_scripts.lua from ZGB_AmmoCatalog.lua - do not edit by hand.
    Standard rounds of calibers vanilla already has are NOT here: they reuse the
    vanilla item (Base.Bullets9mm, Base.556Bullets, Base.ShotgunShells ...).
    VERIFY: Count = rounds per spawned stack; compare with a vanilla bullet item.
*/
module ZGB
{
    imports { Base }
]] }
local ids = {}
for id in pairs(ZGB.AmmoCatalog.CALIBERS) do ids[#ids + 1] = id end
table.sort(ids)
for _, calId in ipairs(ids) do
    local cal = ZGB.AmmoCatalog.CALIBERS[calId]
    for _, v in ipairs(ZGB.AmmoCatalog.variantsFor(calId)) do
        if not v.isVanilla then
            out[#out + 1] = string.format([[

    item %s
    {
        DisplayCategory = Ammo,
        ItemType        = base:normal,
        DisplayName     = %s %s,
        Icon            = %s,
        Weight          = %s,
        Count           = 5,
        Tags            = ZGBAmmo,
    }
]], v.item:match("^ZGB%.(.+)$"), cal.label, v.label, ICONS[calId] or ICONS[cal.group] or "556Bullets",
                tostring(WEIGHT[calId] or WEIGHT[cal.group] or 0.015))
        end
    end
end
out[#out + 1] = "}\n"
write("scripts/ZGB_items_ammo.txt", table.concat(out))

-- ---------------------------------------------------------------- spent casings
out = { [[
/*
    ZE Guns Of Bohemia - spent casings (dropped by the iso view addon).
    GENERATED by tools/gen_scripts.lua from ZGB_AmmoCatalog.CASINGS - do not edit by hand.
*/
module ZGB
{
    imports { Base }
]] }
local done = {}
for _, group in ipairs(ZGB.sortedKeys(ZGB.AmmoCatalog.CASINGS)) do
    local c = ZGB.AmmoCatalog.CASINGS[group]
    if not done[c.id] then
        done[c.id] = true
        out[#out + 1] = string.format([[

    item %s
    {
        DisplayCategory = Junk,
        ItemType        = base:normal,
        DisplayName     = %s,
        Icon            = %s,
        Weight          = 0.005,
        Tags            = ZGBCasing,
    }
]], c.id, c.displayName, group == "shotgun" and "ShotgunShells" or "Bullets9mm")
    end
end
out[#out + 1] = "}\n"
write("scripts/ZGB_items_casings.txt", table.concat(out))
