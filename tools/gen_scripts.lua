--[[
    Regenerates the item-script skeletons from the Lua catalogs, so the .txt
    files can never drift from the data. Run from the repo root after editing
    any file in Defs/ or ZGB_AmmoCatalog.lua:

        lua5.1 tools/gen_scripts.lua

    Writes ZGB_items_weapons.txt, ZGB_items_magazines.txt, ZGB_items_parts.txt
    ZGB_items_ammo.txt and ZGB_items_casings.txt.
]]
local ROOT = "Contents/mods/ZEGunsOfBohemiaCore/42/media/"
package.path = ROOT .. "lua/shared/?.lua;" .. package.path
local realPrint = print
print = function() end          -- silence mod logging
require "ZGB/Defs/ZGB_Def_Parts"
require "ZGB/Defs/ZGB_Def_Weapons"
require "ZGB/Factory/ZGB_AmmoCatalog"
require "ZGB/Defs/ZGB_Def_Models"
require "ZGB/ZGB_Visuals"
print = realPrint
assert(#ZGB.WeaponFactory.errors == 0 and #ZGB.MagazineFactory.errors == 0 and #ZGB.PartFactory.errors == 0,
       "catalogue has errors - run the tests")

local function write(path, text)
    local f = assert(io.open(ROOT .. path, "w"))
    f:write(text); f:close()
    print("wrote " .. path)
end

-- ---------------------------------------------------------------- weapons
-- Models, icons and attachment points come from tools/gen_models.lua (ZGB_models.txt).
-- Every attachment drawn by vanilla (see ZGB_Visuals: "rendered") gets a
-- ModelWeaponPart line: its visual twin item -> its model, mounted by "anchor"
-- on the gun model's channel point (scope / canon / stock / sling / recoilpad).
local out = { [[
/*
    ZE Guns Of Bohemia - weapon item SKELETONS.
    GENERATED by tools/gen_scripts.lua from ZGB_Def_Weapons.lua - do not edit by hand.

    Only identity + visuals live here. Damage, range, ammo, MaxAmmo, magazine,
    reload type, sounds and animations are written at boot by
    ZGB_ScriptApply.lua from the factory spec.
    => Never put MaxAmmo / AmmoType / anims here; the spec is the truth.

    VERIFY: field names follow Build 42 style (WeaponSprite / WorldStaticModel
    with a module prefix, ModelWeaponPart order). Compare with a vanilla gun.
*/
module ZGB
{
    imports { Base }
]] }
for _, s in ipairs(ZGB.WeaponFactory.all()) do
    local lines = {}
    for _, p in ipairs(ZGB.PartFactory.all()) do
        if ZGB.Visuals.mode(p) == "rendered" and ZGB.Attachments.isCompatible(s, p.fullType) then
            lines[#lines + 1] = string.format("        ModelWeaponPart = %s %s anchor %s,", ZGB.Visuals.twinOf(p),
                ZGB.MODULE .. "." .. p.id, ZGB.Visuals.CHANNEL_POINT[p.vanillaPartType])
        end
    end
    out[#out + 1] = string.format([[

    item %s
    {
        DisplayCategory = Firearm,
        ItemType        = base:weapon,
        SubCategory     = Firearm,
        DisplayName     = %s,
        Ranged          = TRUE,
        IsAimedFirearm  = TRUE,
        Icon            = ZGB_%s,
        WeaponSprite    = %s,
        WorldStaticModel = %s,
        Tags            = ZGBWeapon,
%s
    }
]], s.id, s.displayName, s.id, ZGB.MODULE .. "." .. s.id, ZGB.MODULE .. "." .. s.id, table.concat(lines, "\n"))
end
out[#out + 1] = "}\n"
write("scripts/ZGB_items_weapons.txt", table.concat(out))

