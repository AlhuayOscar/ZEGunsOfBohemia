]], c.id, c.displayName, c.id, c.id)
    end
end
out[#out + 1] = "}\n"
write("scripts/ZGB_items_casings.txt", table.concat(out))

-- ------------------------------------------------------------ B42 ammo type registry
-- `AmmoType = zgb:...` in a script only works once the id is registered; the game runs
-- media/registries.lua of every enabled mod before it loads scripts.
local reg = { "-- GENERATED by tools/gen_scripts.lua from ZGB_AmmoCatalog.lua - do not edit by hand.",
              "-- Registers our ammo items as B42 ammo types (vanilla rounds keep their base: ids)." }
for _, r in ipairs(ZGB.AmmoCatalog.registrations()) do
    reg[#reg + 1] = string.format('AmmoType.register("%s", "%s")', r[1], r[2])
end
write("registries.lua", table.concat(reg, "\n") .. "\n")

