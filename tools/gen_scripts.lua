--[[
    Regenerates the item-script skeletons from the Lua catalogs, so the .txt
    files can never drift from the data. Run from the repo root after editing
    ZGB_Def_Parts.lua or ZGB_AmmoCatalog.lua:

        lua tools/gen_scripts.lua
]]
local ROOT = "Contents/mods/ZEGunsOfBohemiaCore/42/media/"
package.path = ROOT .. "lua/shared/?.lua;" .. package.path
local realPrint = print
print = function() end          -- silence mod logging
require "ZGB/Defs/ZGB_Def_Parts"
require "ZGB/Factory/ZGB_AmmoCatalog"
print = realPrint

local function write(path, text)
    local f = assert(io.open(ROOT .. path, "w"))
    f:write(text); f:close()
    print("wrote " .. path)
end

-- ---------------------------------------------------------------- parts
local out = { [[
/*
    ZE Guns Of Bohemia - attachment item skeletons.
    GENERATED by tools/gen_scripts.lua from ZGB_Def_Parts.lua - do not edit by hand.
    Rules + stats live in Lua. When a part gets a 3D model, switch it to the
    vanilla WeaponPart type (zero stat modifiers) and add ModelWeaponPart lines
    to the gun so it renders.
*/
module ZGB
{
    imports { Base }
]] }
for _, p in ipairs(ZGB.PartFactory.all()) do
    out[#out + 1] = string.format([[

    item %s
    {
        DisplayCategory = WeaponPart,
        ItemType        = base:normal,
        DisplayName     = %s,
        Icon            = Scope,
        Weight          = 0.2,
        Tags            = ZGBPart,
    }
]], p.id, p.displayName)
end
out[#out + 1] = "}\n"
write("scripts/ZGB_items_parts.txt", table.concat(out))

-- ---------------------------------------------------------------- ammo
local ICONS = { ["12ga"] = "ShotgunShells", ["22lr"] = "Bullets9mm", ["9x19"] = "Bullets9mm",
                ["38spl"] = "Bullets38", ["45acp"] = "Bullets45", ["44mag"] = "Bullets44" }
local WEIGHT = { ["12ga"] = 0.04, ["22lr"] = 0.005, ["308win"] = 0.03, ["762x39"] = 0.02, ["44mag"] = 0.02 }

out = { [[
/*
    ZE Guns Of Bohemia - ammo variant items.
    GENERATED by tools/gen_scripts.lua from ZGB_AmmoCatalog.lua - do not edit by hand.
    Standard rounds of calibers vanilla already has are NOT here: they reuse the
    vanilla item (Base.Bullets9mm, Base.556Bullets, Base.ShotgunShells ...).
    VERIFY: Count = rounds per spawned stack; compare with a vanilla bullet item.
*/
module ZGB
{
    imports { Base }
]] }
local ids = {}
for id in pairs(ZGB.AmmoCatalog.CALIBERS) do ids[#ids + 1] = id end
table.sort(ids)
for _, calId in ipairs(ids) do
    local cal = ZGB.AmmoCatalog.CALIBERS[calId]
    for _, v in ipairs(ZGB.AmmoCatalog.variantsFor(calId)) do
        if not v.isVanilla then
            out[#out + 1] = string.format([[

    item %s
    {
        DisplayCategory = Ammo,
        ItemType        = base:normal,
        DisplayName     = %s %s,
        Icon            = %s,
        Weight          = %s,
        Count           = 5,
        Tags            = ZGBAmmo,
    }
]], v.item:match("^ZGB%.(.+)$"), cal.label, v.label, ICONS[calId] or "556Bullets",
                tostring(WEIGHT[calId] or 0.015))
        end
    end
end
out[#out + 1] = "}\n"
write("scripts/ZGB_items_ammo.txt", table.concat(out))
