        DisplayName     = %s,
        Icon            = ZGB_%s,
        WorldStaticModel = ZGB.%s,
        Weight          = 0.005,
        Tags            = ZGBCasing,
    }
]], c.id, c.displayName, c.id, c.id)
    end
end
