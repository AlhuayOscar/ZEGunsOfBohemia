-- ---------------------------------------------------------------- parts
out = { [[
/*
    ZE Guns Of Bohemia - attachment item skeletons.
    GENERATED by tools/gen_scripts.lua from ZGB_Def_Parts.lua - do not edit by hand.
    Rules + stats live in Lua; these are what the player carries.

    Vis_<Id> items are VISUAL TWINS of the attachments vanilla can draw
    (ZGB_Visuals "rendered"): real WeaponPart items with zero modifiers that
    the core attaches next to our own part so vanilla shows the model. Players
    never get them in loot. VERIFY: weaponpart field names / MountOn format.
*/
module ZGB
{
    imports { Base }
]] }
for _, p in ipairs(ZGB.PartFactory.all()) do
    local model = ZGB.ModelFactory.partModel(p)
    out[#out + 1] = string.format([[

    item %s
    {
        DisplayCategory = WeaponPart,
        ItemType        = base:normal,
        DisplayName     = %s,
        Icon            = ZGB_%s,
%s        Weight          = 0.2,
    }
]], p.id, p.displayName, p.id, model and ("        WorldStaticModel = ZGB." .. p.id .. ",\n") or "")
    if ZGB.Visuals.mode(p) == "rendered" then
        local guns = {}
        for _, s in ipairs(ZGB.WeaponFactory.all()) do
            if ZGB.Attachments.isCompatible(s, p.fullType) then guns[#guns + 1] = s.fullType end
        end
        out[#out + 1] = string.format([[

    item Vis_%s
    {
        DisplayCategory = WeaponPart,
        ItemType        = base:weaponpart,
        PartType        = %s,
        DisplayName     = %s,
        Icon            = ZGB_%s,
        WorldStaticModel = ZGB.%s,
        Weight          = 0.0,
        MountOn         = %s,
    }
]], p.id, p.vanillaPartType, p.displayName, p.id, p.id, table.concat(guns, "; "))
    end
end
out[#out + 1] = "}\n"
write("scripts/ZGB_items_parts.txt", table.concat(out))

-- ---------------------------------------------------------------- ammo
-- per caliber first, then per caliber group
local ICONS = { ["22lr"] = "Bullets9mm", ["9x19"] = "Bullets9mm", ["38spl"] = "Bullets38", ["45acp"] = "Bullets45",
                ["45colt"] = "Bullets45", ["44mag"] = "Bullets44",
                pistol = "Bullets9mm", revolver = "Bullets38", rifle = "556Bullets", full_rifle = "308Bullets",
                magnum_rifle = "308Bullets", shotgun = "ShotgunShells" }
local WEIGHT = { ["22lr"] = 0.005, ["50bmg"] = 0.12, ["338lm"] = 0.05,
                 pistol = 0.012, revolver = 0.015, rifle = 0.015, full_rifle = 0.03, magnum_rifle = 0.05, shotgun = 0.04 }

out = { [[
/*
    ZE Guns Of Bohemia - ammo variant items.
    GENERATED by tools/gen_scripts.lua from ZGB_AmmoCatalog.lua - do not edit by hand.
    Standard rounds of calibers vanilla already has are NOT here: they reuse the
    vanilla item (Base.Bullets9mm, Base.556Bullets, Base.ShotgunShells ...).
    VERIFY: Count = rounds per spawned stack; compare with a vanilla bullet item.
*/
module ZGB
{
    imports { Base }
]] }
local ids = {}
for id in pairs(ZGB.AmmoCatalog.CALIBERS) do ids[#ids + 1] = id end
table.sort(ids)
for _, calId in ipairs(ids) do
    local cal = ZGB.AmmoCatalog.CALIBERS[calId]
    for _, v in ipairs(ZGB.AmmoCatalog.variantsFor(calId)) do
        if not v.isVanilla then
            out[#out + 1] = string.format([[

    item %s
    {
        DisplayCategory = Ammo,
        ItemType        = base:normal,
        DisplayName     = %s %s,
        Icon            = %s,
        Weight          = %s,
        Count           = 5,
        AmmoType        = %s,
        Tags            = %s,
    }
]], v.item:match("^ZGB%.(.+)$"), cal.label, v.label, ICONS[calId] or ICONS[cal.group] or "556Bullets",
                tostring(WEIGHT[calId] or WEIGHT[cal.group] or 0.015), AC.registryId(v.item),
                cal.group == "shotgun" and "base:ammo;base:shotgunshell" or "base:ammo")
        end
    end
end
out[#out + 1] = "}\n"
write("scripts/ZGB_items_ammo.txt", table.concat(out))

