print = realPrint
assert(#ZGB.WeaponFactory.errors == 0 and #ZGB.MagazineFactory.errors == 0 and #ZGB.PartFactory.errors == 0,
       "catalogue has errors - run the tests")

local AC = ZGB.AmmoCatalog

local function write(path, text)
    local f = assert(io.open(ROOT .. path, "w"))
    f:write(text); f:close()
    print("wrote " .. path)
end

-- ---------------------------------------------------------------- weapons
-- Models, icons and attachment points come from tools/gen_models.lua (ZGB_models.txt).
-- Every attachment drawn by vanilla (see ZGB_Visuals: "rendered") gets a
-- ModelWeaponPart line: its visual twin item -> its model, mounted by "anchor"
-- on the gun model's channel point (scope / canon / stock / sling / recoilpad).
local out = { [[
/*
    ZE Guns Of Bohemia - weapon item SKELETONS.
    GENERATED by tools/gen_scripts.lua from ZGB_Def_Weapons.lua - do not edit by hand.

    Only identity + visuals live here. Damage, range, ammo, MaxAmmo, magazine,
    reload type, sounds and animations are written at boot by
    ZGB_ScriptApply.lua from the factory spec.
    => Never put MaxAmmo / anims here by hand; the spec is the truth. AmmoType IS written
       here (from the spec): the game creates an ammo type's bullet tracer config only
       when it reads it in an item script; set later by DoParam, firing crashed.

    Every other field (fire timing, aim cone, chamber, muzzle flash, equip / aim / jam
    sounds, tags) is copied from the gun's vanilla template (spec.vanillaGun,
    tools/data/vanilla_guns.lua), minus what the factory owns.
*/
module ZGB
{
    imports { Base }
]] }
-- Everything a vanilla gun has that the factory does not decide comes from its
-- template (spec.vanillaGun): fire timing, aim cone, chamber, muzzle flash, equip /
-- aim / jam / casing sounds, tags... Without these our guns fired with no recoil,
-- no muzzle flash and the wrong timing (first in-game test).
local VANILLA = dofile("tools/data/vanilla_guns.lua")
local OWN = {}                        -- lower-case field names the skeleton or ScriptApply write
for _, k in ipairs({ "DisplayCategory", "ItemType", "SubCategory", "DisplayName", "Ranged", "IsAimedFirearm",
                     "Icon", "WeaponSprite", "WorldStaticModel", "StaticModel", "ModelWeaponPart", "AmmoBox",
                     "SwingAnim", "IdleAnim", "RunAnim",                    -- the view provider's
                     "Aimingtime", "Reloadtime", "Projectilecount" }) do   -- vanilla spellings of ours
    OWN[k:lower()] = true
end
local function inherited(spec)
    local own = {}
    for k in pairs(OWN) do own[k] = true end
    for _, kv in ipairs(ZGB.ScriptApply.paramsFor(spec)) do own[kv[1]:lower()] = true end
    local tmpl = assert(VANILLA[spec.vanillaGun], spec.id .. ": vanillaGun '" .. tostring(spec.vanillaGun) .. "' not in tools/data/vanilla_guns.lua")
    local out = {}
    for _, kv in ipairs(tmpl) do
        if not own[kv[1]:lower()] then out[#out + 1] = string.format("        %-24s = %s,", kv[1], kv[2]) end
    end
    return out
end

for _, s in ipairs(ZGB.WeaponFactory.all()) do
    local lines = {}
    for _, p in ipairs(ZGB.PartFactory.all()) do
        if ZGB.Visuals.mode(p) == "rendered" and ZGB.Attachments.isCompatible(s, p.fullType) then
            lines[#lines + 1] = string.format("        ModelWeaponPart = %s %s anchor %s,", ZGB.Visuals.twinOf(p),
                ZGB.MODULE .. "." .. p.id, ZGB.Visuals.CHANNEL_POINT[p.vanillaPartType])
        end
    end
    out[#out + 1] = string.format([[

    item %s
    {
        DisplayCategory = Firearm,
        ItemType        = base:weapon,
        SubCategory     = Firearm,
        DisplayName     = %s,
        Ranged          = TRUE,
        IsAimedFirearm  = TRUE,
        Icon            = ZGB_%s,
        WeaponSprite    = %s,
        WorldStaticModel = %s,
        AmmoType        = %s,
%s
        /* from vanilla %s */
%s
    }
]], s.id, s.displayName, s.id, ZGB.MODULE .. "." .. s.id, ZGB.MODULE .. "." .. s.id, AC.registryId(s.ammo), table.concat(lines, "\n"),
    s.vanillaGun, table.concat(inherited(s), "\n"))
end
out[#out + 1] = "}\n"
write("scripts/ZGB_items_weapons.txt", table.concat(out))

