--[[
    Writes CREDITS.txt (repo root and inside the Core mod) for every third-party
    asset: models from tools/model_sources.lua and sounds from
    Defs/ZGB_Def_Sounds.lua. Called by gen_models.lua and gen_sounds.lua; can
    also run alone:  lua5.1 tools/gen_credits.lua
]]
local CORE = "Contents/mods/ZEGunsOfBohemiaCore/42/media/"
package.path = CORE .. "lua/shared/?.lua;" .. package.path
local realPrint = print
print = function() end
require "ZGB/Defs/ZGB_Def_Sounds"
print = realPrint

local Sources = dofile("tools/model_sources.lua")
local lines = { "ZE Guns Of Bohemia - credits for third-party assets",
    "GENERATED by tools/gen_credits.lua from tools/model_sources.lua and ZGB_Def_Sounds.lua - do not edit by hand.", "",
    "Everything not listed here (code, placeholder models, icons, textures) is the mod's own work.", "",
    "== 3D MODELS", "" }
local packs = {}
for k in pairs(Sources.PACKS) do packs[#packs + 1] = k end
table.sort(packs)
for _, key in ipairs(packs) do
    local p, used = Sources.PACKS[key], {}
    for id, src in pairs(Sources.MODELS) do if src.pack == key then used[#used + 1] = id end end
    table.sort(used)
    if #used > 0 and p.perModel then
        -- one credit per model (Sketchfab): several of our items may share one model
        local byUid, uids = {}, {}
        for _, id in ipairs(used) do
            local src = Sources.MODELS[id]
            if not byUid[src.uid] then byUid[src.uid] = { credit = src.credit, ids = {} }; uids[#uids + 1] = src.uid end
            table.insert(byUid[src.uid].ids, id)
        end
        table.sort(uids, function(a, b) return byUid[a].credit.title < byUid[b].credit.title end)
        for _, uid in ipairs(uids) do
            local c = byUid[uid].credit
            lines[#lines + 1] = string.format("\"%s\" by %s (%s), via Sketchfab", c.title, c.author, c.license)
            lines[#lines + 1] = "  " .. c.url
            lines[#lines + 1] = "  Used for: " .. table.concat(byUid[uid].ids, ", ") .. " (resized, re-textured and reduced for the game)"
            lines[#lines + 1] = ""
        end
    elseif #used > 0 then
        lines[#lines + 1] = string.format("%s by %s (%s)", p.title, p.author, p.license)
        lines[#lines + 1] = "  " .. p.url
        lines[#lines + 1] = "  Used for: " .. table.concat(used, ", ")
        lines[#lines + 1] = ""
    end
end
lines[#lines + 1] = "== SOUNDS"
lines[#lines + 1] = ""
for _, key in ipairs({ "ffsl", "zer0_sol" }) do
    local s = ZGB.Sounds.SOURCES[key]
    lines[#lines + 1] = string.format("%s by %s (%s)", s.title, s.author, s.license)
    lines[#lines + 1] = "  " .. s.url
    lines[#lines + 1] = ""
end
local text = table.concat(lines, "\n")
for _, path in ipairs({ "CREDITS.txt", "Contents/mods/ZEGunsOfBohemiaCore/42/CREDITS.txt" }) do
    local f = assert(io.open(path, "wb")); f:write(text); f:close()
end
print("wrote CREDITS.txt")
